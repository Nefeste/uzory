interface Named { name: string; lab: Lab }

const DICT: Named[] = NAMES.map(([h, name]) => ({ name, lab: rgbToLab(parseHex(h)!) }));

function ranked(lab: Lab): Named[] {
  return [...DICT].sort((a, b) => deltaOK(a.lab, lab) - deltaOK(b.lab, lab));
}

/**
 * Названия нитей узора: ближайшее из словаря; одинаковые различаются приставкой по тому,
 * чем отличаются от ближайшей к словарному цвету: светлее / темнее или бледнее / ярче.
 * Если и с приставкой повтор — следующее по близости название.
 */
export function nameThreads(colors: number[]): string[] {
  const labs = colors.map(rgbToLab);
  const names = labs.map((l) => ranked(l)[0].name);
  const byName = new Map<string, number[]>();
  names.forEach((n, i) => byName.set(n, [...(byName.get(n) ?? []), i]));
  const out = [...names];
  for (const [base, group] of byName) {
    if (group.length < 2) continue;
    const dict = DICT.find((d) => d.name === base)!.lab;
    const keep = group.reduce((a, b) => (deltaOK(labs[a], dict) <= deltaOK(labs[b], dict) ? a : b));
    const [kl, kc] = labToLch(labs[keep]);
    for (const i of group) {
      if (i === keep) continue;
      const [l, c] = labToLch(labs[i]);
      const dl = l - kl;
      const dc = c - kc;
      const [bl, bc] = labToLch(dict);
      const prefix = Math.abs(dl) >= Math.abs(dc) ? (dl > 0 ? 'светло' : 'тёмно') : dc < 0 ? 'бледно' : 'ярко';
      // «светло-белая» и «тёмно-чёрная» не бывают: у краёв — соседнее название
      const silly = (prefix === 'светло' && bl > 0.9) || (prefix === 'тёмно' && bl < 0.3) || (prefix === 'бледно' && bc < 0.03);
      out[i] = silly ? '' : `${prefix}-${base}`;
    }
  }
  // повторы после приставок — следующее по близости свободное название
  const used = new Set<string>();
  for (let i = 0; i < out.length; i++) {
    if (out[i] && !used.has(out[i])) {
      used.add(out[i]);
      continue;
    }
    const alt = ranked(labs[i]).find((d) => !used.has(d.name) && !out.includes(d.name));
    out[i] = alt ? alt.name : `${out[i]} ${i + 1}`;
    used.add(out[i]);
  }
  return out;
}
